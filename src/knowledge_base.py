if "SYMPTOM_ALIASES" not in dir():
    SYMPTOM_ALIASES = dict(SYMPTOM_ALIASES_EXPANSION_V4)
else:
    SYMPTOM_ALIASES.update(SYMPTOM_ALIASES_EXPANSION_V4)
def all_condition_names() -> list[str]:
    return [c.name for c in CONDITIONS]


def get_condition(name: str) -> ConditionProfile | None:
    key = name.strip().lower()
    for c in CONDITIONS:
        if c.name.lower() == key:
            return c
    return None


def normalize_symptom_token(token: str) -> str:
    t = token.strip().lower().replace("_", " ")
    t = " ".join(t.split())
    return SYMPTOM_ALIASES.get(t, t)


def collect_symptom_vocabulary() -> set[str]:
    vocab: set[str] = set(SYMPTOM_ALIASES.keys()) | set(SYMPTOM_ALIASES.values())
    for c in CONDITIONS:
        vocab.update(c.symptoms.keys())
    return vocab


# Exclude catch-all labels from the selectable differential. These labels are too
# broad to be useful as condition-level outputs; weak/ambiguous symptom patterns
# are handled by the predictor's explicit nonspecific/low-evidence result instead.
# Keep this filter after the curated profiles so the source entries remain easy to
# audit and can be re-evaluated against a future clinically reviewed dataset.
_filtered_conditions = (
    condition for condition in CONDITIONS
    if condition.name not in {
        "Influenza-like illness",
        "Nonspecific viral syndrome",
    }
)
# De-duplicate repeated profile definitions so a condition cannot occupy two
# ranks or create a duplicate label in the dataset.
_seen_condition_names: set[str] = set()
CONDITIONS = tuple(
    condition for condition in _filtered_conditions
    if not (condition.name.strip().casefold() in _seen_condition_names
            or _seen_condition_names.add(condition.name.strip().casefold()))
)
del _filtered_conditions, _seen_condition_names
