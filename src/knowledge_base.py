"""Professional primary-care knowledge base for symptom ranking.

Replaces the old balanced 41-disease Kaggle toy dataset. Conditions are common
in general practice, with realistic characteristic symptoms, prevalence priors,
age/sex applicability, and conservative educational support text.

Still an educational demonstration — not a diagnostic or prescribing system.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable


@dataclass(frozen=True)
class ConditionProfile:
    name: str
    prevalence: float  # relative prior (higher = more common)
    symptoms: dict[str, float]  # normalized symptom -> characteristic weight 0-1
    description: str
    precautions: tuple[str, ...] = ()
    medications: tuple[str, ...] = ()
    diet: tuple[str, ...] = ()
    age_groups: tuple[str, ...] = ("Child", "Adult", "Older adult")
    sexes: tuple[str, ...] = ("Male", "Female")
    pregnancy_ok: bool = True
    category: str = "general"


def S(**weights: float) -> dict[str, float]:
    """Build a symptom weight map; keys are normalized with spaces."""
    return {k.replace("_", " ").strip().lower(): float(v) for k, v in weights.items()}


